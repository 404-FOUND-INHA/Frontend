import { describe, expect, it } from 'vitest'
import { isValidIsoDate } from './calendarDate'

describe('isValidIsoDate', () => {
  it.each([
    ['2024-02-29', '윤년의 2월 29일'],
    ['2000-02-29', '400의 배수 해는 윤년'],
    ['2026-02-28', '평년 2월 마지막 날'],
    ['2026-12-31', '연말'],
    ['2026-04-30', '30일까지 있는 달의 마지막 날'],
  ])('%s 은(는) 유효하다 (%s)', (value) => {
    expect(isValidIsoDate(value)).toBe(true)
  })

  it.each([
    ['2025-02-29', '평년의 2월 29일'],
    ['1900-02-29', '100의 배수지만 400의 배수가 아닌 해는 평년'],
    ['2026-02-30', '2월 30일'],
    ['2026-04-31', '30일까지 있는 달의 31일'],
    ['2026-13-01', '13월'],
    ['2026-00-10', '0월'],
    ['2026-01-00', '0일'],
    ['2026-12-32', '32일'],
    ['2026-1-1', '자릿수가 부족한 형식'],
    ['20261201', '구분자가 없는 형식'],
    ['2026/12/01', '다른 구분자'],
    ['2026-12-01T00:00:00', '시각이 붙은 값'],
    [' 2026-12-01', '앞 공백'],
    ['2026-12-01 ', '뒤 공백'],
    ['', '빈 문자열'],
    ['abcd-ef-gh', '숫자가 아닌 값'],
  ])('%s 은(는) 유효하지 않다 (%s)', (value) => {
    expect(isValidIsoDate(value)).toBe(false)
  })
})
